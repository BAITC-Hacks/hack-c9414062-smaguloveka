def _forms(n):
    if n[-1] in "ая":
        st = n[:-1]
        return {n} | {st + e for e in ("ы", "и", "е", "у", "ой", "ей")}
    return {n} | {n + e for e in ("а", "у", "ом", "ем", "е", "ым", "ға", "ге", "қа", "ке", "ды", "ді", "ты", "ті")}


NAME_RE = re.compile(r"\b(" + "|".join(sorted({f for n in FIRST_NAMES for f in _forms(n)}, key=len, reverse=True)) + r")\b")
SKIP_FIRST = set("и а но с у к о в на по от до за что это как так вот ну".split())


def _cap(w: str) -> str:
    return w[:1].upper() + w[1:] if w else w


def restore_case(text: str, names: list[str] | None = None) -> str:
    """Имя + отчество → с заглавных; имена из списка участников → с заглавной; первая буква реплики — заглавная."""
    def rep(m):
        first, patr = m.group(1), m.group(2)
        if first in SKIP_FIRST or len(patr) < 7:
            return m.group(0)
        return f"{_cap(first)} {_cap(patr)}"
    t = PATRON_RE.sub(rep, text)
    t = NAME_RE.sub(lambda m: _cap(m.group(1)), t)
    for n in names or []:
        for part in n.split():
            stem = part.lower()[:max(3, len(part) - 2)]
            if len(stem) < 3:
                continue
            t = re.sub(r"\b(" + re.escape(stem) + r"[а-яёәғқңөұүһі]*)", lambda m: _cap(m.group(1)), t)
    t = t.strip()
    t = _cap(t)
    if t and t[-1] not in ".!?…":
        t += "."
    return t


def lang_tag(text: str) -> str:
    words = re.findall(r"[а-яёәғқңөұүһі]+", text.lower())
    if not words:
        return "RU"
    kz = sum(1 for w in words if (set(w) & KZ_LETTERS) or w in KZ_WORDS)
    ru = sum(1 for w in words if w in RU_WORDS)
    kz_r, ru_r = kz / len(words), ru / len(words)
    if kz_r >= 0.35 and ru_r < 0.06:
        return "KZ"
    if kz_r >= 0.1 or (kz >= 2 and ru >= 1):
        return "RU+KZ"
    return "RU"


def fmt_t(sec: float) -> str:
    sec = int(round(sec))
    return f"{sec // 3600:02d}:{sec % 3600 // 60:02d}:{sec % 60:02d}"
